-- Jalankan pada branch Neon yang sama dengan Auth URL aplikasi.
CREATE TABLE IF NOT EXISTS management_members (
    user_id text PRIMARY KEY,
    display_name text NOT NULL,
    enabled boolean NOT NULL DEFAULT true
);
REVOKE ALL ON management_members FROM PUBLIC;
ALTER TABLE management_members ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS management_documents (
    id text PRIMARY KEY,
    number integer GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    title text NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 160),
    description text NOT NULL DEFAULT '' CHECK (length(description) <= 500),
    category text NOT NULL CHECK (length(trim(category)) BETWEEN 1 AND 60),
    url text NOT NULL DEFAULT '',
    action_type text NOT NULL DEFAULT 'link' CHECK (action_type IN ('link', 'vehicle_picker')),
    icon text NOT NULL DEFAULT '▤',
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS management_vehicles (
    id text PRIMARY KEY,
    sort_order integer GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 120),
    url text NOT NULL DEFAULT '',
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS management_vehicles_name_unique
    ON management_vehicles (lower(name));
REVOKE ALL ON management_documents, management_vehicles FROM PUBLIC;
ALTER TABLE management_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE management_vehicles ENABLE ROW LEVEL SECURITY;
