-- Jalankan pada branch Neon yang sama dengan Auth URL aplikasi.
CREATE TABLE IF NOT EXISTS management_roles (
    id text PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (length(trim(name)) BETWEEN 1 AND 80),
    can_manage_menus boolean NOT NULL DEFAULT false,
    can_manage_users boolean NOT NULL DEFAULT false,
    is_system boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO management_roles (id, name, can_manage_menus, can_manage_users, is_system) VALUES
    ('admin', 'Admin', true, true, true),
    ('member', 'Anggota', false, false, true)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS management_members (
    user_id text PRIMARY KEY,
    display_name text NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    role_id text NOT NULL DEFAULT 'member' REFERENCES management_roles(id)
);
ALTER TABLE management_members ADD COLUMN IF NOT EXISTS role_id text NOT NULL DEFAULT 'member' REFERENCES management_roles(id);
UPDATE management_members SET role_id='member' WHERE role_id NOT IN ('admin','member');
DELETE FROM management_roles WHERE id NOT IN ('admin','member');
UPDATE management_roles SET name='Admin', can_manage_menus=true, can_manage_users=true, is_system=true WHERE id='admin';
UPDATE management_roles SET name='Anggota', can_manage_menus=false, can_manage_users=false, is_system=true WHERE id='member';
ALTER TABLE management_members ALTER COLUMN role_id SET DEFAULT 'member';
REVOKE ALL ON management_members FROM PUBLIC;
ALTER TABLE management_members ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON management_roles FROM PUBLIC;
ALTER TABLE management_roles ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS management_documents (
    id text PRIMARY KEY,
    number integer GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    title text NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 160),
    description text NOT NULL DEFAULT '' CHECK (length(description) <= 500),
    category text NOT NULL DEFAULT '',
    url text NOT NULL DEFAULT '',
    action_type text NOT NULL DEFAULT 'link' CHECK (action_type IN ('link', 'vehicle_picker')),
    icon text NOT NULL DEFAULT '▤',
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE management_documents DROP CONSTRAINT IF EXISTS management_documents_category_check;
ALTER TABLE management_documents DROP CONSTRAINT IF EXISTS management_documents_category_length_check;
ALTER TABLE management_documents ADD CONSTRAINT management_documents_category_length_check
    CHECK (length(category) <= 60);

CREATE TABLE IF NOT EXISTS management_vehicles (
    id text PRIMARY KEY,
    sort_order integer GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 120),
    url text NOT NULL DEFAULT '',
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS management_vehicles_name_unique
    ON management_vehicles (lower(name));
REVOKE ALL ON management_documents, management_vehicles FROM PUBLIC;
ALTER TABLE management_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE management_vehicles ENABLE ROW LEVEL SECURITY;
